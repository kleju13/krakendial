  const DICTS = { en, pl };
  let lang = "en";

  // "auto" (or anything unknown) follows the browser: the first of its languages we have.
  function resolve(want) {
    if (DICTS[want]) return want;
    const prefs = (typeof navigator !== "undefined" && (navigator.languages || [navigator.language])) || [];
    for (const p of prefs) {
      const id = String(p || "").slice(0, 2).toLowerCase();
      if (DICTS[id]) return id;
    }
    return "en";
  }

  function t(key, vars) {
    let s = DICTS[lang][key] ?? en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
    return s;
  }

  window.KrakenI18n = {
    LANGS,
    resolve,
    t,
    // Switches the language; returns true when it changed, so callers know to rebuild.
    use(want) {
      const next = resolve(want);
      if (next === lang) return false;
      lang = next;
      return true;
    },
    get lang() {
      return lang;
    },
    get locale() {
      return (LANGS.find((l) => l.id === lang) || LANGS[0]).locale;
    },
  };
